"""Regenerate PDF/PNG report figures from current exports and saved MLP runs."""
from pathlib import Path
import csv
import hashlib
import json
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages
from matplotlib.colors import Normalize
from matplotlib.patches import FancyArrowPatch
import numpy as np
from config import CONFIG

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "figures"
DATASETS = {"openneuro": "OpenNeuro", "brainlat": "BrainLat"}
METHODS = {"granger": "Granger", "lingam": "VARLiNGAM", "pcmci": "PCMCI"}
CLASSES = ("CN", "AD", "FTD")
COLORS = ("#237aab", "#d67b26", "#9b4c98")
MASK = ~np.eye(19, dtype=bool)


def dataset_subjects(key):
    """Return processed subjects after applying dataset-specific exclusions."""
    excluded = set(CONFIG.get("excluded_subjects", {}).get(key, []))
    subjects = sorted((ROOT / "data_hgcn_ready" / key / "subjects").glob("sub-*"))
    return [subject for subject in subjects if subject.name not in excluded]


def save(fig, name):
    """Save a Matplotlib figure as matching PDF and PNG report assets."""
    fig.savefig(OUT / f"{name}.pdf", bbox_inches="tight", facecolor="white")
    fig.savefig(OUT / f"{name}.png", dpi=200, bbox_inches="tight", facecolor="white")


def figure(name, caption, page=None, height="0.70"):
    """Build a LaTeX figure block that points at a generated PDF asset."""
    options = rf"width=\textwidth,height={height}\textheight,keepaspectratio"
    if page is not None:
        options += f",page={page}"
    return ("\\begin{figure}[H]\n\\centering\n"
            + rf"\includegraphics[{options}]{{figures/{name}.pdf}}" + "\n"
            + rf"\caption{{{caption}}}" + "\n\\end{figure}\n")


def table(headers, rows, caption):
    """Build a small LaTeX booktabs table from rows of scalar values."""
    return ("\\begin{table}[H]\n\\centering\\small\n"
            + r"\begin{tabular}{" + "l" * len(headers) + "}\n\\toprule\n"
            + " & ".join(headers) + " \\\\\n\\midrule\n"
            + "\n".join(" & ".join(map(str, row)) + r" \\" for row in rows)
            + "\n\\bottomrule\n\\end{tabular}\n" + rf"\caption{{{caption}}}"
            + "\n\\end{table}\n")


def replace_block(text, name, body, old_input):
    """Replace an autogenerated LaTeX block, or insert it at a legacy input."""
    start, end = f"% BEGIN AUTO {name}", f"% END AUTO {name}"
    replacement = start + "\n" + body + "\n" + end
    if start in text:
        return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: replacement, text, flags=re.S)
    if old_input not in text:
        raise ValueError(f"Missing insertion point: {name}")
    return text.replace(old_input, replacement)


def main():
    """Regenerate connectivity figures, classifier figures, and report blocks."""
    OUT.mkdir(exist_ok=True)
    plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})
    stats, inventory, connectivity, classification, provenance = [], [], [], [], {}
    with PdfPages(OUT / "connectivity_networks.pdf") as network_pdf, PdfPages(OUT / "connectivity_summary.pdf") as summary_pdf:
        for page, (key, display) in enumerate(DATASETS.items(), 1):
            # Load one dataset at a time so class averages and thresholds stay
            # dataset-specific instead of mixing OpenNeuro and BrainLat scales.
            subjects = dataset_subjects(key)
            labels = np.array([json.loads((s / "y.json").read_text())["label"] for s in subjects])
            counts = [int((labels == c).sum()) for c in range(3)]
            epochs = sorted({json.loads((s / "metadata.json").read_text())["n_epochs"] for s in subjects})
            if len(epochs) != 1 or not all(counts):
                raise ValueError(
                    f"{display} export is inconsistent: "
                    f"epochs={epochs}, class_counts={counts}"
                )
            inventory.append([display, *counts, len(subjects), epochs[0]])
            digest = hashlib.sha256()
            for s in subjects:
                for f in [s / "X.npy", s / "y.json", s / "metadata.json", *[s / f"A_{m}_normal.npy" for m in METHODS]]:
                    digest.update(str(f.relative_to(ROOT)).encode())
                    digest.update(f.read_bytes())
            provenance[key] = {"subjects": [s.name for s in subjects], "sha256_inputs": digest.hexdigest(), "n_epochs": epochs[0]}
            networks, nax = plt.subplots(3, 3, figsize=(13, 12), layout="constrained")
            heatmaps, hax = plt.subplots(3, 3, figsize=(13, 12), layout="constrained")
            summary, sax = plt.subplots(2, 3, figsize=(12, 6), layout="constrained")
            networks.suptitle(f"{display} | Class-average directed connectivity", fontsize=17)
            heatmaps.suptitle(f"{display} | Full class-average matrices", fontsize=17)
            summary.suptitle(f"{display} | Connectivity above the display threshold", fontsize=15)
            theta = np.pi / 2 - np.arange(19) * 2 * np.pi / 19
            pos = np.column_stack((np.cos(theta), np.sin(theta)))
            rows = []
            for row, (method, title) in enumerate(METHODS.items()):
                # Threshold only for display: the heatmaps remain unthresholded,
                # while networks and summary bars show the strongest edges.
                matrices = np.stack([np.load(s / f"A_{method}_normal.npy") for s in subjects])
                assert matrices.shape == (len(subjects), 19, 19) and np.isfinite(matrices).all()
                means = np.stack([matrices[labels == c].mean(axis=0) for c in range(3)])
                threshold = float(np.quantile(means[:, MASK], .8))
                vmax = max(float(means.max()), 1e-12)
                numbers, weights = [], []
                for c, cls in enumerate(CLASSES):
                    a = means[c]
                    keep = MASK & (a > threshold)
                    n = int(keep.sum())
                    weight = float(a[keep].mean()) if n else 0.
                    stats.append(dict(dataset=key, method=method, clinical_class=cls, subjects=counts[c],
                                      threshold=threshold, edges=n, density=n / 342, mean_weight=weight))
                    rows.append([title, cls, f"{threshold:.3f}", n, f"{n / 342:.3f}", f"{weight:.3f}"])
                    numbers.append(n)
                    weights.append(weight)
                    ax = nax[row, c]
                    for target, source in zip(*np.where(keep)):
                        source_pos = (float(pos[source, 0]), float(pos[source, 1]))
                        target_pos = (float(pos[target, 0]), float(pos[target, 1]))
                        ax.add_patch(FancyArrowPatch(source_pos, target_pos, arrowstyle="-|>", mutation_scale=8,
                            connectionstyle="arc3,rad=0.10", shrinkA=6, shrinkB=7,
                            linewidth=.35 + 1.3 * a[target, source] / vmax,
                            color=plt.cm.viridis(a[target, source] / vmax), alpha=.65))
                    ax.scatter(*pos.T, c="#f0f3f5", edgecolors="#334155", s=55, zorder=3)
                    for p, channel in zip(pos, CONFIG["channel_order"]):
                        ax.text(*(p * 1.13), channel, ha="center", va="center", fontsize=9)
                    ax.set(xlim=(-1.30, 1.30), ylim=(-1.30, 1.30), aspect="equal")
                    ax.set_title(f"{title} | {cls} (n={counts[c]})\n{n} edges; q80={threshold:.3f}", fontsize=11)
                    ax.axis("off")
                    hm = hax[row, c].imshow(a, vmin=0, vmax=vmax, cmap="viridis")
                    hax[row, c].set_title(f"{title} | {cls} (n={counts[c]})")
                    hax[row, c].set_xticks(range(19), CONFIG["channel_order"], rotation=90, fontsize=7)
                    hax[row, c].set_yticks(range(19), CONFIG["channel_order"], fontsize=7)
                    hax[row, c].set(xlabel="Source", ylabel="Target")
                heatmaps.colorbar(hm, ax=hax[row, :], shrink=.8, label="Normalized weight")
                networks.colorbar(plt.cm.ScalarMappable(norm=Normalize(0, vmax), cmap="viridis"),
                                  ax=nax[row, :], shrink=.65, label="Normalized weight")
                for ax, values, label in [(sax[0, row], numbers, "Directed edges"), (sax[1, row], weights, "Mean retained weight")]:
                    bars = ax.bar(CLASSES, values, color=COLORS)
                    ax.bar_label(bars, fmt="%.3f" if label.startswith("Mean") else "%d", padding=3)
                    ax.set(ylim=(0, max(values) * 1.23 if max(values) else 1), ylabel=label, title=title)
            network_pdf.savefig(networks, bbox_inches="tight")
            summary_pdf.savefig(summary, bbox_inches="tight")
            for fig, suffix in [(networks, "networks"), (heatmaps, "heatmaps"), (summary, "summary")]:
                save(fig, f"connectivity_{key}_{suffix}")
                plt.close(fig)
            connectivity.append(rf"\subsection{{{display}}}" + "\n"
                + f"This dataset contains {len(subjects)} subjects ({counts[0]} CN, {counts[1]} AD and {counts[2]} FTD), with {epochs[0]} retained epochs per subject.\n"
                + figure("connectivity_networks", f"{display}: class-average directed networks. Arrows run from source to target; color and width encode normalized weight. Circular positions indicate channel order, not anatomy. Scales and thresholds are shared across classes within each method.", page)
                + figure(f"connectivity_{key}_heatmaps", f"{display}: unthresholded class-average matrices. Rows are targets, columns are sources; each method shares its color scale across classes.")
                + figure("connectivity_summary", f"{display}: edge counts and mean retained weights above the dataset- and method-specific 80th percentile.", page, "0.40")
                + table(["Method", "Class", "$q_{d,m}$", "Edges", "Density", "Mean weight"], rows, f"{display}: thresholded class-average connectivity statistics."))

            result_file = ROOT / "results" / "mlp" / key / "classifier_results.json"
            results = json.loads(result_file.read_text())
            provenance[key]["sha256_mlp_results"] = hashlib.sha256(result_file.read_bytes()).hexdigest()
            first = results["granger"]
            # Every method in one classifier run must use the same split, so a
            # method comparison is not confounded by different held-out subjects.
            splits = [first[k] for k in ("train_subjects", "validation_subjects", "test_subjects")]
            assert len(set(sum(splits, []))) == sum(map(len, splits))
            assert set(sum(splits, [])) == {f"{key}:{s.name}" for s in subjects}
            rows = []
            cmfig, axes = plt.subplots(1, 3, figsize=(11, 3.6), layout="constrained")
            cmfig.suptitle(f"{display} | MLP held-out confusion matrices", fontsize=15)
            for ax, (method, title) in zip(axes, METHODS.items()):
                r = results[method]
                assert all(r[k] == first[k] for k in ("train_subjects", "validation_subjects", "test_subjects"))
                cm = np.asarray(r["confusion_matrix"])
                assert cm.sum() == len(splits[2])
                assert np.isclose(np.mean(cm.diagonal() / cm.sum(axis=1)), r["balanced_accuracy"])
                assert np.isclose(cm.trace() / cm.sum(), r["accuracy"])
                rows.append([title, f"{r['balanced_accuracy']:.3f}", f"{r['accuracy']:.3f}", r["training"]["best_epoch"], r["training"]["epochs_run"]])
                ax.imshow(cm, cmap="Blues", vmin=0, vmax=7)
                ax.set_xticks(range(3), CLASSES)
                ax.set_yticks(range(3), CLASSES)
                ax.set(xlabel="Predicted class", ylabel="True class", title=title)
                for i in range(3):
                    for j in range(3):
                        ax.text(j, i, str(cm[i, j]), ha="center", va="center", color="white" if cm[i, j] > 3.5 else "black", fontsize=14)
            save(cmfig, f"mlp_{key}_confusion")
            plt.close(cmfig)
            fig, ax = plt.subplots(figsize=(8, 4), layout="constrained")
            x = np.arange(3)
            for offset, metric, color, title in [(-.18, "balanced_accuracy", COLORS[0], "Balanced accuracy"), (.18, "accuracy", COLORS[1], "Accuracy")]:
                bars = ax.bar(x + offset, [results[m][metric] for m in METHODS], .36, label=title, color=color)
                ax.bar_label(bars, fmt="%.3f", padding=3)
            ax.axhline(1/3, linestyle="--", color="gray", label="Uniform-chance balanced accuracy")
            ax.set(xticks=x, xticklabels=list(METHODS.values()), ylim=(0, 1.15), ylabel="Test score", title=f"{display} | MLP performance")
            ax.legend(loc="upper center", ncol=2, fontsize=8)
            save(fig, f"mlp_{key}_performance")
            plt.close(fig)
            support = np.asarray(first["confusion_matrix"]).sum(axis=1)
            classification.append(rf"\subsection{{{display}: independent within-dataset evaluation}}" + "\n"
                + f"The split contains {len(splits[0])} training, {len(splits[1])} validation and {len(splits[2])} test subjects. Test support is {support[0]} CN, {support[1]} AD and {support[2]} FTD.\n"
                + table(["Adjacency", "Balanced accuracy", "Accuracy", "Best epoch", "Epochs run"], rows, f"{display}: saved MLP test results, seed 42.")
                + figure(f"mlp_{key}_performance", f"{display}: MLP test scores by connectivity method.", height="0.32")
                + figure(f"mlp_{key}_confusion", f"{display}: test confusion matrices; true classes on rows and predictions on columns.", height="0.28"))

    # Original PNG names now contain both datasets in explicitly separate panels.
    for suffix in ("networks", "summary"):
        fig, axes = plt.subplots(1, 2, figsize=(26, 12 if suffix == "networks" else 6), layout="constrained")
        for ax, key in zip(axes, DATASETS):
            ax.imshow(plt.imread(OUT / f"connectivity_{key}_{suffix}.png"))
            ax.axis("off")
        fig.savefig(OUT / f"connectivity_{suffix}.png", dpi=180, bbox_inches="tight")
        plt.close(fig)
    for name in ("connectivity_summary.csv", "connectivity_by_dataset.csv"):
        with (OUT / name).open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(stats[0]))
            writer.writeheader()
            writer.writerows(stats)
    (OUT / "report_inputs.json").write_text(json.dumps(provenance, indent=2))
    report = ROOT / "docs" / "report_sintetico_en.tex"
    text = report.read_text()
    for name, body, filename in [
        ("INVENTORY", table(["Dataset", "CN", "AD", "FTD", "Total", "Epochs/subject"], inventory, "Current processed exports, analyzed separately by dataset."), "dataset_inventory"),
        ("CONNECTIVITY", "\n".join(connectivity), "connectivity_results"),
        ("CLASSIFICATION", "\n".join(classification), "classification_results")]:
        text = replace_block(text, name, body, rf"\input{{docs/generated/{filename}.tex}}")
    report.write_text(text)
    print("Rebuilt PDF/PNG figures, replaced original network/summary files, and embedded tables and figure references in LaTeX.")


if __name__ == "__main__":
    main()
